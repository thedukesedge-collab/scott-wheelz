#!/usr/bin/env python3
"""Refloat Glow: writes the LCM_POLL segment that carries the LCM
firmware name (e.g. "VPBL-1a2b3c4"), with its precomputed CRC, as a header
the GCC build force-includes (see vesc_serial.c, LCM_POLL_SEGMENT).

usage: lcm_tag.py NAME out.h
"""
import sys


def crc16(data):
    crc = 0
    for b in data:
        crc ^= b << 8
        for _ in range(8):
            crc = ((crc << 1) ^ 0x1021) if crc & 0x8000 else crc << 1
            crc &= 0xFFFF
    return crc


name, out = sys.argv[1], sys.argv[2]
if not 0 < len(name) <= 19 or not name.isascii():
    sys.exit("name must be 1-19 ASCII characters")
payload = bytes([0x24, 0x65, 0x18]) + name.encode()
c = crc16(payload)
packet = bytes([0x02, len(payload)]) + payload + bytes([c >> 8, c & 0xFF, 0x03])
with open(out, "w") as f:
    f.write(f"/* generated by lcm/tools/lcm_tag.py: LCM_POLL with name \"{name}\" */\n")
    f.write("#define LCM_POLL_SEGMENT " + ", ".join(f"0x{b:02x}" for b in packet) + "\n")
    f.write(f"#define LCM_POLL_SEGMENT_LENGTH {len(packet)}U\n")
    f.write(f"#define LCM_FIRMWARE_NAME \"{name}\"\n")
